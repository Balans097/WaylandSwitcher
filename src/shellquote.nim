## shellquote.nim — безопасное экранирование строк для /bin/sh и systemd.

import std/strutils

proc shellQuote*(s: string): string =
  ## Оборачивает строку в одинарные кавычки, чтобы shell воспринимал её как
  ## один литеральный аргумент. Внутренние одинарные кавычки заменяются
  ## последовательностью '\'' (закрыть кавычку, экранированная кавычка,
  ## открыть кавычку). Результат пригоден и для поля ExecStart юнита systemd.
  "'" & replace(s, "'", "'\\''") & "'"
