#!/bin/sh
#
# reinstall.sh — устанавливает уже собранный бинарник WaylandSwitcher,
# заменяя собой ручную последовательность
# systemctl stop / cp / chmod / chown / systemctl start.
#
# Компиляция в этот скрипт не входит — соберите проект самостоятельно
# перед запуском:
#   nim c --threads:on -d:release WaylandSwitcher.nim
#
# Почему не делать установку вручную (как раньше):
#   1. Простой 'cp' поверх работающего бинарника — НЕ атомарная операция.
#      Если что-то прервёт копирование (нехватка места на диске, обрыв
#      сессии и т.д.), можно получить повреждённый или пустой файл —
#      демон после такого либо не запустится, либо завершится крашем.
#   2. Ручной скрипт не делает резервную копию и не умеет откатиться
#      при ошибке.
#   3. Ручной скрипт всегда останавливает и запускает службу, даже если
#      она не была активна (например, при первой установке).
#
# Вместо этого здесь используется встроенная команда самого приложения —
# 'wayland-switcher -R' (см. runReinstall в src/setup.nim), которая:
#   • останавливает службу ТОЛЬКО если она была активна, и запоминает это;
#   • копирует новый бинарник во временный файл рядом с целевым путём и
#     заменяет старый через rename() — атомарную операцию на одном
#     разделе диска (старый бинарник никогда не существует в «битом»
#     промежуточном состоянии);
#   • делает резервную копию текущего бинарника (.bak) и автоматически
#     откатывается на неё, если rename() или что-либо до него не удалось;
#   • выставляет права 0755 и владельца root:root на новый файл;
#   • обновляет systemd-юнит и запускает службу обратно, только если она
#     была активна до переустановки.
#
# Использование:
#   nim c --threads:on -d:release WaylandSwitcher.nim   # сборка (отдельно)
#   sudo ./reinstall.sh                                  # установка
# Запускать из директории, где лежит собранный бинарник ./WaylandSwitcher.

set -e   # остановиться при первой ошибке

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
cd "$SCRIPT_DIR"

if [ ! -f "./WaylandSwitcher" ]; then
  echo "Ошибка: ./WaylandSwitcher не найден в $SCRIPT_DIR" >&2
  echo "Сначала соберите проект:" >&2
  echo "  nim c --threads:on -d:release WaylandSwitcher.nim" >&2
  exit 1
fi

if [ ! -x "./WaylandSwitcher" ]; then
  echo "Ошибка: ./WaylandSwitcher найден, но не является исполняемым файлом." >&2
  echo "Проверьте права (chmod +x) или пересоберите проект." >&2
  exit 1
fi

echo "Установка через встроенную команду переустановки..."
# runReinstall сам разберётся с остановкой/запуском службы, правами,
# резервной копией и откатом при ошибке — см. описание выше.
sudo ./WaylandSwitcher -R
